def gather_market_context(ticker: str, timeframe: str = "1Hour") -> dict:
    """
    Collects comprehensive market context for the agentic prompt:
    - Price, ATR, RSI, MACD, Bollinger, EMA trend, 52-week range from yfinance
    - SPY 5-day trend (bull/bear market proxy) + ticker-SPY correlation
    - VIX level and regime classification
    - Sector ETF 5-day trend
    - Realized volatility, support/resistance, consecutive candle direction
    - Earnings date, beta
    - Google News headlines
    """
    decision_timeframe = normalize_ai_timeframe(timeframe)
    timeframe_spec = _ai_timeframe_spec(decision_timeframe)
    candle_interval = timeframe_spec["interval"]
    context_period = timeframe_spec["period"]
    bars_per_trading_day = timeframe_spec["bars_per_day"]

    ctx = {
        "ticker": ticker,
        "timeframe": decision_timeframe,
        "price": None,
        "prev_close": None,
        "change_pct": None,
        "week52_high": None,
        "week52_low": None,
        "range_position_pct": None,
        "atr": None,
        "rsi": None,
        "macd_hist": None,
        "macd_crossover": "NONE",  # BULLISH_CROSS / BEARISH_CROSS / NONE
        "volume_ratio": None,      # today vs 20d avg
        "market_cap": None,
        "sector": None,
        "industry": None,
        # EMA trend structure
        "ema_9": None,
        "ema_21": None,
        "ema_50": None,
        "sma_200": None,
        "ema_trend": "UNKNOWN",    # STRONG_BULL / BULL / BEAR / STRONG_BEAR
        # Bollinger Bands
        "boll_upper": None,
        "boll_lower": None,
        "boll_width_pct": None,    # width as % of price (squeeze detection)
        "boll_position": None,     # where price sits 0-100 inside the bands
        # Support / Resistance
        "support": None,
        "resistance": None,
        # Realized volatility
        "realized_vol_30d": None,  # annualized 30-day realized vol %
        # Consecutive direction
        "consec_green": 0,
        "consec_red": 0,
        # Correlation with SPY
        "corr_spy_30d": None,
        # Earnings & Beta
        "next_earnings": None,
        "days_to_earnings": None,
        "beta": None,
        # Macro
        "spy_trend": "UNKNOWN",
        "spy_change_5d": None,
        "vix_level": None,
        "vix_regime": "UNKNOWN",
        "sector_etf": _get_sector_etf(ticker),
        "sector_trend": "UNKNOWN",
        "sector_change_5d": None,
        # News
        "headlines": [],
        "headline_count": 0,
        "is_crypto": any(ticker.upper().endswith(b) for b in ["USD", "USDT", "USDC", "BTC", "ETH"]),
    }

    spy_returns = None  # used for correlation later

    # ── 1. Ticker fundamentals via yfinance ──────────────────────────────
    try:
        yf_ticker = ticker.upper()
        if ctx["is_crypto"]:
            for suffix in ["USDT", "USDC", "USD"]:
                if yf_ticker.endswith(suffix):
                    yf_ticker = yf_ticker[: -len(suffix)] + "-" + suffix
                    break

        t = yf.Ticker(yf_ticker)
        hist = t.history(period=context_period, interval=candle_interval)
        if hist is not None and not hist.empty and timeframe_spec.get("resample"):
            hist = hist.resample(
                timeframe_spec["resample"],
                origin="start_day",
                offset="0min" if ctx["is_crypto"] else "9h30min",
            ).agg({
                "Open": "first",
                "High": "max",
                "Low": "min",
                "Close": "last",
                "Volume": "sum",
            }).dropna(subset=["Open", "High", "Low", "Close"])
        hist = _completed_history_only(hist, decision_timeframe, ctx["is_crypto"])

        if hist is not None and not hist.empty:
            close = hist["Close"]
            high = hist["High"]
            low = hist["Low"]

            ctx["price"] = float(close.iloc[-1])
            ctx["prev_close"] = float(close.iloc[-2]) if len(hist) >= 2 else ctx["price"]
            ctx["change_pct"] = ((ctx["price"] - ctx["prev_close"]) / ctx["prev_close"] * 100) if ctx["prev_close"] else 0
            # Intraday vendor retention is shorter than 52 weeks for the fast
            # intervals, so use daily candles only for the 52-week range.
            range_hist = hist
            if decision_timeframe != "1Day":
                try:
                    daily_hist = t.history(period="1y", interval="1d")
                    if daily_hist is not None and not daily_hist.empty:
                        range_hist = daily_hist
                except Exception:
                    pass
            ctx["week52_high"] = float(range_hist["High"].max())
            ctx["week52_low"] = float(range_hist["Low"].min())

            rng = ctx["week52_high"] - ctx["week52_low"]
            if rng > 0:
                ctx["range_position_pct"] = round((ctx["price"] - ctx["week52_low"]) / rng * 100, 1)

            # ATR(14)
            tr = (high - low).combine(
                (high - close.shift(1)).abs(), max
            ).combine(
                (low - close.shift(1)).abs(), max
            )
            ctx["atr"] = round(float(tr.ewm(span=14, adjust=False).mean().iloc[-1]), 4)

            # RSI(14)
            delta = close.diff()
            gain = delta.clip(lower=0).ewm(com=13, adjust=False).mean()
            loss = (-delta.clip(upper=0)).ewm(com=13, adjust=False).mean()
            rs = gain / loss.replace(0, 1e-9)
            rsi_series = 100 - (100 / (1 + rs))
            ctx["rsi"] = round(float(rsi_series.iloc[-1]), 1)

            # MACD histogram + crossover detection
            ema12 = close.ewm(span=12, adjust=False).mean()
            ema26 = close.ewm(span=26, adjust=False).mean()
            macd_line = ema12 - ema26
            signal_line = macd_line.ewm(span=9, adjust=False).mean()
            macd_hist_series = macd_line - signal_line
            ctx["macd_hist"] = round(float(macd_hist_series.iloc[-1]), 8)
            if len(macd_hist_series) >= 2:
                prev_h = float(macd_hist_series.iloc[-2])
                curr_h = float(macd_hist_series.iloc[-1])
                if prev_h <= 0 < curr_h:
                    ctx["macd_crossover"] = "BULLISH_CROSS"
                elif prev_h >= 0 > curr_h:
                    ctx["macd_crossover"] = "BEARISH_CROSS"

            # EMA trend structure: 9 > 21 > 50 > SMA200 = STRONG_BULL
            ctx["ema_9"] = round(float(close.ewm(span=9, adjust=False).mean().iloc[-1]), 4)
            ctx["ema_21"] = round(float(close.ewm(span=21, adjust=False).mean().iloc[-1]), 4)
            ctx["ema_50"] = round(float(close.ewm(span=50, adjust=False).mean().iloc[-1]), 4)
            if len(close) >= 200:
                ctx["sma_200"] = round(float(close.rolling(200).mean().iloc[-1]), 8)
            e9, e21, e50, s200 = ctx["ema_9"], ctx["ema_21"], ctx["ema_50"], ctx["sma_200"]
            if e9 and e21 and e50:
                if s200 and e9 > e21 > e50 > s200:
                    ctx["ema_trend"] = "STRONG_BULL"
                elif e9 > e21 > e50:
                    ctx["ema_trend"] = "BULL"
                elif s200 and e9 < e21 < e50 < s200:
                    ctx["ema_trend"] = "STRONG_BEAR"
                elif e9 < e21 < e50:
                    ctx["ema_trend"] = "BEAR"
                else:
                    ctx["ema_trend"] = "MIXED"

            # Bollinger Bands (20, 2)
            sma20 = close.rolling(20).mean()
            std20 = close.rolling(20).std()
            boll_u = sma20 + 2 * std20
            boll_l = sma20 - 2 * std20
            if not np.isnan(boll_u.iloc[-1]):
                ctx["boll_upper"] = round(float(boll_u.iloc[-1]), 8)
                ctx["boll_lower"] = round(float(boll_l.iloc[-1]), 8)
                bw = ctx["boll_upper"] - ctx["boll_lower"]
                ctx["boll_width_pct"] = round(bw / ctx["price"] * 100, 2) if ctx["price"] else None
                if bw > 0:
                    ctx["boll_position"] = round((ctx["price"] - ctx["boll_lower"]) / bw * 100, 1)

            # Prior-bar structure deliberately excludes the latest candle so a
            # breakout can be detected on the current completed decision bar.
            lookback = min(20, max(1, len(hist) - 1))
            prior_low = low.iloc[-(lookback + 1):-1] if len(hist) > 1 else low
            prior_high = high.iloc[-(lookback + 1):-1] if len(hist) > 1 else high
            ctx["support"] = round(float(prior_low.min()), 8)
            ctx["resistance"] = round(float(prior_high.max()), 8)

            # Realized volatility over roughly 30 trading days of hourly bars.
            # Annualize with hourly regular-session observations, not daily
            # scaling, so the value remains statistically meaningful.
            realized_window = 30 * bars_per_trading_day
            if len(close) >= realized_window + 1:
                log_returns = np.log(close / close.shift(1)).dropna()
                rv = float(log_returns.iloc[-realized_window:].std()) * np.sqrt(252 * bars_per_trading_day) * 100
                ctx["realized_vol_30d"] = round(rv, 1)

            # Consecutive green/red candles
            greens, reds = 0, 0
            for j in range(len(close) - 1, 0, -1):
                if float(close.iloc[j]) > float(close.iloc[j - 1]):
                    greens += 1
                else:
                    break
            for j in range(len(close) - 1, 0, -1):
                if float(close.iloc[j]) < float(close.iloc[j - 1]):
                    reds += 1
                else:
                    break
            ctx["consec_green"] = greens
            ctx["consec_red"] = reds

            # Volume ratio (last one-hour bar vs 20-bar average)
            if "Volume" in hist.columns and hist["Volume"].iloc[-1] > 0:
                avg_vol = hist["Volume"].rolling(20).mean().iloc[-1]
                if avg_vol > 0:
                    ctx["volume_ratio"] = round(float(hist["Volume"].iloc[-1] / avg_vol), 2)

            # Save ticker returns for SPY correlation later
            correlation_window = 30 * bars_per_trading_day
            if len(close) >= correlation_window + 1:
                ticker_returns = np.log(close / close.shift(1)).dropna().values[-correlation_window:]
            else:
                ticker_returns = None

        # Info (may fail for crypto)
        try:
            info = t.fast_info
            ctx["market_cap"] = getattr(info, "market_cap", None)
            ctx["sector"] = getattr(info, "sector", None)
            ctx["industry"] = getattr(info, "industry", None)
        except Exception:
            pass

        # Beta remains part of general ticker info.  Earnings dates use the
        # shared validated calendar service so Quant AI and Screener agree.
        try:
            full_info = t.info
            ctx["beta"] = full_info.get("beta")
        except Exception:
            pass
        try:
            earnings = build_earnings_watch(ticker)
            if earnings.get("event_date"):
                ctx["next_earnings"] = earnings["event_date"]
                ctx["days_to_earnings"] = earnings.get("days_to_event")
        except Exception:
            pass

    except Exception as e:
        print(f"[ai_indicator] yfinance error for {ticker}: {e}")
        ticker_returns = None

    # ── 2. SPY 5-day trend + correlation ─────────────────────────────────
    try:
        spy = yf.Ticker("SPY")
        spy_hist = spy.history(period=context_period, interval=candle_interval)
        if spy_hist is not None and not spy_hist.empty and timeframe_spec.get("resample"):
            spy_hist = spy_hist.resample(timeframe_spec["resample"], origin="start_day", offset="9h30min").agg({
                "Open": "first", "High": "max", "Low": "min",
                "Close": "last", "Volume": "sum",
            }).dropna(subset=["Close"])
        if spy_hist is not None and len(spy_hist) >= 5:
            five_day_bars = min(5 * bars_per_trading_day, len(spy_hist) - 1)
            spy_5d_start = float(spy_hist["Close"].iloc[-(five_day_bars + 1)])
            spy_latest = float(spy_hist["Close"].iloc[-1])
            ctx["spy_change_5d"] = round((spy_latest - spy_5d_start) / spy_5d_start * 100, 2)
            ctx["spy_trend"] = "BULLISH" if ctx["spy_change_5d"] > 0.3 else "BEARISH" if ctx["spy_change_5d"] < -0.3 else "NEUTRAL"

            # 30-day correlation
            try:
                correlation_window = 30 * bars_per_trading_day
                if ticker_returns is not None and len(spy_hist["Close"]) >= correlation_window + 1:
                    spy_ret = np.log(spy_hist["Close"] / spy_hist["Close"].shift(1)).dropna().values[-correlation_window:]
                    if len(spy_ret) == len(ticker_returns):
                        ctx["corr_spy_30d"] = round(float(np.corrcoef(ticker_returns, spy_ret)[0, 1]), 2)
            except Exception:
                pass
    except Exception as e:
        print(f"[ai_indicator] SPY trend error: {e}")

    # ── 3. VIX level ─────────────────────────────────────────────────────
    try:
        if not ctx["is_crypto"]:
            vix = yf.Ticker("^VIX")
            vix_hist = vix.history(period=context_period, interval=candle_interval)
            if vix_hist is not None and not vix_hist.empty:
                ctx["vix_level"] = round(float(vix_hist["Close"].iloc[-1]), 1)
                v = ctx["vix_level"]
                ctx["vix_regime"] = "LOW" if v < 15 else "MEDIUM" if v < 25 else "HIGH"
        else:
            ctx["vix_regime"] = "CRYPTO"
    except Exception as e:
        print(f"[ai_indicator] VIX error: {e}")

    # ── 4. Sector ETF trend ──────────────────────────────────────────────
    try:
        if ctx["sector_etf"] not in ("SPY",) or not ctx["is_crypto"]:
            sec = yf.Ticker(ctx["sector_etf"])
            sec_hist = sec.history(period=context_period, interval=candle_interval)
            if sec_hist is not None and not sec_hist.empty and timeframe_spec.get("resample"):
                sec_hist = sec_hist.resample(timeframe_spec["resample"], origin="start_day", offset="9h30min").agg({
                    "Open": "first", "High": "max", "Low": "min",
                    "Close": "last", "Volume": "sum",
                }).dropna(subset=["Close"])
            if sec_hist is not None and len(sec_hist) >= 5:
                five_day_bars = min(5 * bars_per_trading_day, len(sec_hist) - 1)
                sec_start = float(sec_hist["Close"].iloc[-(five_day_bars + 1)])
                sec_latest = float(sec_hist["Close"].iloc[-1])
                ctx["sector_change_5d"] = round((sec_latest - sec_start) / sec_start * 100, 2)
                ctx["sector_trend"] = (
                    "BULLISH" if ctx["sector_change_5d"] > 0.2
                    else "BEARISH" if ctx["sector_change_5d"] < -0.2
                    else "NEUTRAL"
                )
    except Exception as e:
        print(f"[ai_indicator] Sector ETF error: {e}")

    return ctx


