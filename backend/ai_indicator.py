def _fallback_sentiment(ticker: str, news_items: list) -> dict:
    """Rule-based sentiment scoring as a fallback."""
    articles = [
        dict(item) if isinstance(item, dict) else {"title": str(item), "source": "Unknown source", "url": "", "excerpt": ""}
        for item in (news_items or [])
        if (item.get("title") if isinstance(item, dict) else str(item)).strip()
    ]
    headlines = [article["title"] for article in articles]
    if not headlines:
        return {
            "score": 0.0,
            "confidence": 0.0,
            "summary": f"No recent attributable news headlines were available for {ticker}. News sentiment is neutral because there is insufficient headline evidence; this does not forecast price direction.",
            "key_factor": "No attributable headlines",
            "headline_count": 0,
            "headlines": [],
            "articles": [],
        }

    pos_words = ["beat", "beats", "surge", "surged", "growth", "upgrade", "upgraded", "gain", "gains", "climb", "climbs", "record high", "success", "profit", "profits", "launch", "bullish", "strong", "outperform", "rise", "rises", "positive", "expand", "acquisition", "rally", "soar", "soars"]
    neg_words = ["miss", "misses", "drop", "drops", "plunge", "plunges", "decline", "declines", "fall", "falls", "loss", "losses", "lawsuit", "complaint", "downgrade", "downgraded", "bearish", "weak", "underperform", "negative", "shrink", "debt", "risk", "hazard", "crack", "struggle", "inflation", "constraint", "constraints", "slow", "slows", "less"]
    
    score = 0.0
    pos_count = 0
    neg_count = 0
    article_analysis = []
    for index, h in enumerate(headlines):
        h_lower = h.lower()
        item_pos = 0
        item_neg = 0
        for pw in pos_words:
            if re.search(rf"\b{re.escape(pw)}\b", h_lower):
                pos_count += 1
                item_pos += 1
        for nw in neg_words:
            if re.search(rf"\b{re.escape(nw)}\b", h_lower):
                neg_count += 1
                item_neg += 1
        item_score = item_pos - item_neg
        item_sentiment = "BULLISH" if item_score > 0 else "BEARISH" if item_score < 0 else "NEUTRAL"
        article_analysis.append({
            "article_index": index + 1,
            "sentiment": item_sentiment,
            "impact": "LOW",
            "relevance": "DIRECT",
            "summary": _clean_news_text(articles[index].get("excerpt") or h, 240),
            "reason": "Keyword fallback from the article title; AI article interpretation was unavailable.",
        })
    
    total_words = pos_count + neg_count
    if total_words > 0:
        score = (pos_count - neg_count) / total_words
    else:
        score = 0.0
    
    direction = "bullish" if score >= 0.40 else "bearish" if score <= -0.40 else "neutral/mixed"
    summary = (
        f"Headline evidence includes: {headlines[0]}. "
        f"Aggregate headline tone is {direction}; this classification reflects headline language only and does not forecast price direction."
    )
    key_factor = headlines[0]
    if len(key_factor) > 60:
        key_factor = key_factor[:57] + "..."

    enriched_articles = []
    for index, article in enumerate(articles):
        enriched_articles.append({**article, **article_analysis[index]})

    return {
        "score": round(score, 2),
        # Title-keyword scoring is deliberately held below the configured AI
        # confidence floor. It is visible context, never a directional veto.
        "confidence": round(min(0.39, 0.25 + 0.03 * min(total_words, 4)), 2),
        "summary": summary,
        "key_factor": key_factor,
        "headline_count": len(headlines),
        "headlines": headlines[:5],
        "articles": enriched_articles[:5],
    }

def get_ai_sentiment(
    ticker: str,
    model: str = None,
    *,
    force_refresh: bool = False,
    articles: list[dict] | None = None,
) -> dict:
    """
    Fetch recent attributable article evidence and use the selected Groq or
    Ollama model for relevance-aware, per-article sentiment analysis. The
    result is cached by ticker and model to prevent rate limits.
    """
    global SENTIMENT_CACHE

    # 1. Check Cache First. Include the prompt version so a deployment cannot
    # reuse sentiment prose generated by an older classifier contract.
    cfg = get_user_config()
    news_model = normalize_ai_model_name(model or getattr(cfg, "AI_INDICATOR_MODEL", "llama-3.3-70b-versatile"))
    sentiment_cache_key = (str(ticker).upper(), news_model, SENTIMENT_CACHE_VERSION)
    cached_entry = SENTIMENT_CACHE.get(sentiment_cache_key, SENTIMENT_CACHE_DURATION)
    if not force_refresh and articles is None and cached_entry is not None:
        return attach_sentiment_metadata(cached_entry['data'])

    # 2. Fetch directly attributable recent article evidence. The classifier
    # receives title, publisher, publication age and a bounded metadata
    # preview when the publisher exposes one; it never pretends to read a
    # paywalled or unavailable full article body.
    articles = (
        [dict(article) for article in articles[:8] if isinstance(article, dict)]
        if articles is not None
        else _fetch_news_articles(ticker, max_articles=8)
    )
    headlines = [article["title"] for article in articles]

    # Local fallback engine when Groq is not available or API key is not configured
    groq_key = getattr(cfg, "GROQ_API_KEY", "")
    is_ollama = news_model.startswith("ollama/") or news_model.startswith("ollama:")
    if not is_ollama and (not _GROQ_AVAILABLE or not groq_key or groq_key in ("", "your_groq_api_key_here")):
        result = attach_sentiment_metadata(_fallback_sentiment(ticker, articles), cfg)
        result["analysis_model"] = "keyword-fallback"
        SENTIMENT_CACHE.set(sentiment_cache_key, {"data": result})
        return result

    try:
        if not headlines:
            result = attach_sentiment_metadata({
                "score": 0.0,
                "confidence": 0.0,
                "summary": "Could not extract headlines.",
                "key_factor": "N/A",
                "headline_count": 0,
                "headlines": [],
                "articles": [],
                "analysis_model": "no-evidence",
            }, cfg)
            SENTIMENT_CACHE.set(sentiment_cache_key, {"data": result})
            return result

        article_evidence = []
        for index, article in enumerate(articles, start=1):
            evidence = (
                f"ARTICLE {index}\n"
                f"Title: {article['title']}\n"
                f"Publisher: {article.get('source', 'Unknown source')}\n"
                f"Published: {article.get('published_at') or 'Unknown'}"
            )
            if article.get("excerpt"):
                evidence += f"\nPublisher preview: {article['excerpt']}"
            article_evidence.append(evidence)
        news_text = "\n\n".join(article_evidence)

        # News is a separate evidence stream. Keep it factual and independent
        # from chart/price analysis so the main decision model can reconcile
        # technical and news bias without contradictory prose.
        prompt = f"""Assess only the supplied recent article evidence for {ticker}.

This is a NEWS-ONLY classifier, not a chart analyst and not a trade-signal generator.
Do not infer RSI, moving averages, channels, support/resistance, momentum, price
direction, or institutional flow unless the article title or publisher preview explicitly
states it. Do not claim to have read a full article when only title/preview metadata is
supplied. If evidence is stale, vague, duplicated, unrelated, or mixed, keep the score
near neutral and lower confidence. Classify benchmark comparisons or articles that only
mention {ticker} incidentally as CONTEXT or IRRELEVANT; they must not drive the aggregate.

Article evidence:
{news_text}

Respond with ONLY valid JSON (no markdown, no code blocks) using these exact keys:
{{
    "score": <float between -1.0 (extremely bearish) and 1.0 (extremely bullish)>,
    "confidence": <float between 0.0 (no confidence) and 1.0 (very confident)>,
    "summary": "<3 concise sentences: first name the most important ticker-specific catalyst supported by the article evidence; second state contrary, mixed, or uncertain evidence; third classify aggregate tone. Do not mention technical chart conditions and do not invent facts.>",
    "key_factor": "<the single concrete article catalyst driving the score, 4-12 words; use 'Mixed/insufficient evidence' when none is dominant>",
    "article_analysis": [
        {{"article_index": <1-{len(articles)}>, "relevance": "<DIRECT|CONTEXT|IRRELEVANT>", "sentiment": "<BULLISH|BEARISH|NEUTRAL>", "impact": "<HIGH|MEDIUM|LOW>", "summary": "<one concise factual sentence summarizing only that article's supplied title/preview>", "reason": "<one factual sentence explaining the classification>"}}
    ]
}}

Article aggregation rules:
- DIRECT means the article is primarily about {ticker}; use full weight.
- CONTEXT means {ticker} is a benchmark, comparison, or secondary subject; use minimal weight.
- IRRELEVANT means an incidental ticker mention; ignore it completely.
- The aggregate score and summary must be driven by DIRECT evidence, with CONTEXT used only as background.

Scoring guide (this must align with the application’s 0-100% display):
- -1.00 to -0.40 = bearish news (0-30%)
- -0.39 to +0.39 = neutral/mixed news (31-69%)
- +0.40 to +1.00 = bullish news (70-100%)
- The score is headline tone, not the probability that price rises.
- A score around +0.32 displays as 66% and is still NEUTRAL, not bearish.

Confidence guide:
- High (0.7-1.0): multiple recent, direct, unambiguous catalysts
- Medium (0.4-0.7): relevant but mixed or indirect headlines
- Low (0.0-0.4): vague, stale, speculative, duplicated, or conflicting headlines
"""

        news_system_msg = (
            "You are a conservative financial-news sentiment classifier. "
            "Follow the supplied schema, distinguish direct from incidental relevance, and never invent facts."
        )
        try:
            output, actual_news_model = _call_llm(
                prompt=prompt,
                system_msg=news_system_msg,
                model=news_model,
                cfg=cfg,
                temperature=0.1,
                max_tokens=1200,
            )
        except Exception:
            if is_ollama or news_model == "openai/gpt-oss-20b":
                raise
            output, actual_news_model = _call_llm(
                prompt=prompt,
                system_msg=news_system_msg,
                model="openai/gpt-oss-20b",
                cfg=cfg,
                temperature=0.1,
                max_tokens=1200,
            )
        sentiment_data = json.loads(output)

        score = max(-1.0, min(1.0, float(sentiment_data.get('score', 0.0))))
        confidence = max(0.0, min(1.0, float(sentiment_data.get('confidence', 0.5))))

        analyses_by_index = {}
        for analysis in sentiment_data.get("article_analysis") or []:
            try:
                article_index = int(analysis.get("article_index"))
            except (TypeError, ValueError, AttributeError):
                continue
            article_sentiment = str(analysis.get("sentiment", "NEUTRAL")).upper()
            article_impact = str(analysis.get("impact", "LOW")).upper()
            article_relevance = str(analysis.get("relevance", "DIRECT")).upper()
            if article_sentiment not in {"BULLISH", "BEARISH", "NEUTRAL"}:
                article_sentiment = "NEUTRAL"
            if article_impact not in {"HIGH", "MEDIUM", "LOW"}:
                article_impact = "LOW"
            if article_relevance not in {"DIRECT", "CONTEXT", "IRRELEVANT"}:
                article_relevance = "IRRELEVANT"
            analyses_by_index[article_index] = {
                "article_index": article_index,
                "sentiment": article_sentiment,
                "impact": article_impact,
                "relevance": article_relevance,
                "summary": _clean_news_text(analysis.get("summary"), 280),
                "reason": _clean_news_text(analysis.get("reason"), 240) or "No article-specific rationale returned.",
            }
        enriched_articles = []
        for index, article in enumerate(articles, start=1):
            analysis = analyses_by_index.get(index, {
                "article_index": index,
                "sentiment": "NEUTRAL",
                "impact": "LOW",
                "relevance": "IRRELEVANT",
                "summary": _clean_news_text(article.get("excerpt") or article.get("title"), 280),
                "reason": "The model did not return an article-specific classification.",
            })
            if not analysis.get("summary"):
                analysis["summary"] = _clean_news_text(article.get("excerpt") or article.get("title"), 280)
            enriched_articles.append({**article, **analysis})

        sentiment_values = {"BULLISH": 1.0, "BEARISH": -1.0, "NEUTRAL": 0.0}
        impact_weights = {"HIGH": 1.5, "MEDIUM": 1.0, "LOW": 0.5}
        relevance_weights = {"DIRECT": 1.0, "CONTEXT": 0.25, "IRRELEVANT": 0.0}
        weighted_total = 0.0
        available_weight = 0.0
        direct_count = 0
        context_count = 0
        for article in enriched_articles:
            relevance = article["relevance"]
            if relevance == "DIRECT":
                direct_count += 1
            elif relevance == "CONTEXT":
                context_count += 1
            weight = impact_weights[article["impact"]] * relevance_weights[relevance]
            weighted_total += sentiment_values[article["sentiment"]] * weight
            available_weight += weight
        score = max(-1.0, min(1.0, weighted_total / available_weight)) if available_weight else 0.0
        evidence_confidence = min(0.90, 0.20 + 0.10 * min(direct_count, 5) + 0.03 * min(context_count, 3) + 0.20 * abs(score))
        if direct_count == 0:
            evidence_confidence = min(evidence_confidence, 0.25)
        confidence = min(confidence, evidence_confidence)
        def _article_rank(article):
            return ({"HIGH": 3, "MEDIUM": 2, "LOW": 1}[article["impact"]], -(article.get("age_hours") or 10_000))

        direct_bullish = sorted(
            (article for article in enriched_articles if article["relevance"] == "DIRECT" and article["sentiment"] == "BULLISH"),
            key=_article_rank,
            reverse=True,
        )
        direct_bearish = sorted(
            (article for article in enriched_articles if article["relevance"] == "DIRECT" and article["sentiment"] == "BEARISH"),
            key=_article_rank,
            reverse=True,
        )
        primary_articles = direct_bullish if score >= 0.40 else direct_bearish if score <= -0.40 else sorted(
            direct_bullish + direct_bearish,
            key=_article_rank,
            reverse=True,
        )
        key_factor = (
            _clean_news_text(primary_articles[0]["title"], 100)
            if primary_articles
            else "Mixed or insufficient directly relevant evidence"
        )
        summary_parts = []
        if direct_bullish:
            summary_parts.append(f"Positive article evidence: {direct_bullish[0]['reason']}")
        if direct_bearish:
            summary_parts.append(f"Negative article evidence: {direct_bearish[0]['reason']}")
        if not summary_parts:
            summary_parts.append("Directly relevant article evidence is neutral, mixed, or insufficient")
        validated_summary = ". ".join(part.rstrip(".!? ") for part in summary_parts[:2]) + "."

        result = attach_sentiment_metadata({
            "score": round(score, 3),
            "confidence": round(confidence, 3),
            "summary": validated_summary,
            "model_summary": _clean_news_text(sentiment_data.get('summary'), 600),
            "key_factor": key_factor,
            "headline_count": len(headlines),
            "headlines": headlines[:5],
            "articles": enriched_articles[:5],
            "analysis_model": actual_news_model,
        }, cfg)

        # Save to cache
        SENTIMENT_CACHE.set(sentiment_cache_key, {"data": result})

        return result

    except json.JSONDecodeError as e:
        print(f"[ai_indicator] JSON parse error for {ticker}, using fallback: {e}")
        result = attach_sentiment_metadata(_fallback_sentiment(ticker, articles), cfg)
        result["analysis_model"] = "keyword-fallback"
        SENTIMENT_CACHE.set(sentiment_cache_key, {"data": result})
        return result
    except Exception as e:
        print(f"[ai_indicator] Error fetching sentiment for {ticker}, using fallback: {e}")
        result = attach_sentiment_metadata(_fallback_sentiment(ticker, articles), cfg)
        result["analysis_model"] = "keyword-fallback"
        SENTIMENT_CACHE.set(sentiment_cache_key, {"data": result})
        return result


SCREENER_NEWS_POLL_SECONDS = 60


def _canonical_news_url(value: str) -> str:
    try:
        parsed = urllib.parse.urlsplit(str(value or ""))
        if parsed.scheme not in {"http", "https"} or not parsed.netloc:
            return ""
        return urllib.parse.urlunsplit((parsed.scheme.lower(), parsed.netloc.lower(), parsed.path, "", ""))
    except (TypeError, ValueError):
        return ""


def _news_article_id(article: dict) -> str:
    normalized_title = re.sub(r"[^a-z0-9]+", " ", str(article.get("title") or "").lower()).strip()
    source = re.sub(r"[^a-z0-9]+", " ", str(article.get("source") or "").lower()).strip()
    identity = "|".join((_canonical_news_url(article.get("url")), normalized_title, source))
    return hashlib.sha256(identity.encode("utf-8")).hexdigest()[:24]


def _news_feed_fingerprint(articles: list[dict]) -> str:
    ordered = [
        f"{_news_article_id(article)}:{int(article.get('published_ts') or 0)}"
        for article in articles
    ]
    return hashlib.sha256("|".join(ordered).encode("utf-8")).hexdigest()[:24]


def _news_provider_label(articles: list[dict], provider_status: dict) -> str:
    providers = {str(article.get("feed_provider") or "").lower() for article in articles}
    if "yahoo" in providers and "google" in providers:
        return "Yahoo Finance + Google News fallback"
    if "google" in providers:
        return "Google News fallback"
    if "yahoo" in providers:
        return "Yahoo Finance"
    if provider_status.get("yahoo") in {"ok", "empty"}:
        return "Yahoo Finance"
    return "Google News fallback"


def _news_article_summary(article: dict) -> str:
    return _clean_news_text(
        article.get("summary")
        or article.get("excerpt")
        or article.get("reason")
        or article.get("title"),
        280,
    )


def build_screener_news_watch(
    ticker: str,
    previous: dict | None = None,
    model: str = None,
    poll_seconds: int = SCREENER_NEWS_POLL_SECONDS,
) -> dict:
    """Check public headline metadata and reclassify only when the feed changes."""
    previous = dict(previous or {})
    checked_ts = time.time()
    checked_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(checked_ts))
    poll_seconds = max(60, int(poll_seconds or SCREENER_NEWS_POLL_SECONDS))

    articles, provider_status = _fetch_news_article_metadata_cached(ticker, max_articles=8)
    successful_provider = any(
        provider_status.get(name) in {"ok", "empty"}
        for name in ("yahoo", "google")
    )
    if not successful_provider:
        failure_count = int(previous.get("failure_count") or 0) + 1
        retry_seconds = min(900, poll_seconds * (2 ** min(failure_count - 1, 4)))
        stale = dict(previous)
        stale.update({
            "enabled": True,
            "status": "stale" if previous.get("initialized") else "unavailable",
            "checked_at": checked_at,
            "failure_count": failure_count,
            "error": "; ".join(provider_status.get("errors") or ["News providers unavailable"]),
            "provider_status": provider_status,
            "new_count": 0,
            "next_check_at": checked_ts + retry_seconds,
        })
        return stale

    feed_fingerprint = _news_feed_fingerprint(articles)
    previous_fingerprint = str(previous.get("feed_fingerprint") or "")
    provider_label = _news_provider_label(articles, provider_status)
    degraded = bool(provider_status.get("errors"))
    if previous.get("initialized") and feed_fingerprint == previous_fingerprint:
        current = dict(previous)
        active_new_count = int(previous.get("new_count") or 0) if checked_ts < float(previous.get("new_until_at") or 0) else 0
        current.update({
            "enabled": True,
            "status": "degraded" if degraded else "current",
            "checked_at": checked_at,
            "last_success_at": checked_at,
            "provider": provider_label,
            "provider_status": provider_status,
            "failure_count": 0,
            "error": "; ".join(provider_status.get("errors") or []),
            "new_count": active_new_count,
            "next_check_at": checked_ts + poll_seconds,
        })
        return current

    enriched = _add_news_article_previews(articles)
    sentiment = get_ai_sentiment(
        ticker,
        model=model,
        force_refresh=True,
        articles=enriched,
    )
    analyzed_articles = []
    for article in sentiment.get("articles") or []:
        if not isinstance(article, dict):
            continue
        normalized = dict(article)
        normalized["id"] = _news_article_id(normalized)
        analyzed_articles.append(normalized)

    display_articles = [
        article for article in analyzed_articles
        if str(article.get("relevance") or "DIRECT").upper() != "IRRELEVANT"
    ][:4]
    prior_seen = {str(value) for value in previous.get("seen_article_ids") or [] if value}
    current_ids = [_news_article_id(article) for article in articles]
    display_ids = [str(article.get("id") or "") for article in display_articles]
    new_count = 0 if not previous.get("initialized") else sum(
        bool(article_id and article_id not in prior_seen) for article_id in display_ids
    )
