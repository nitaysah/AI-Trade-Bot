def _clean_news_text(value: str, maximum: int = 400) -> str:
    text = html_lib.unescape(re.sub(r"<[^>]+>", " ", str(value or "")))
    text = " ".join(text.split()).strip()
    return text[:maximum].rstrip()


def _is_public_news_url(url: str) -> bool:
    """Allow article previews only from publicly routable HTTP(S) hosts."""
    try:
        parsed = urllib.parse.urlparse(str(url or ""))
        if parsed.scheme not in {"http", "https"} or not parsed.hostname:
            return False
        addresses = socket.getaddrinfo(parsed.hostname, parsed.port or (443 if parsed.scheme == "https" else 80))
        return bool(addresses) and all(
            ipaddress.ip_address(address[4][0].split("%", 1)[0]).is_global
            for address in addresses
        )
    except (OSError, ValueError, TypeError):
        return False


class _PublicNewsRedirectHandler(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if not _is_public_news_url(newurl):
            raise urllib.error.URLError("Blocked non-public news redirect")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _article_preview(url: str) -> str:
    """Read only a page's short public metadata description, never its full body."""
    if not _is_public_news_url(url):
        return ""
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        opener = urllib.request.build_opener(_PublicNewsRedirectHandler())
        raw = opener.open(req, timeout=5).read(350_000).decode("utf-8", "ignore")
        patterns = (
            r'<meta[^>]+(?:name|property)=["\'](?:description|og:description|twitter:description)["\'][^>]+content=["\']([^"\']+)',
            r'<meta[^>]+content=["\']([^"\']+)["\'][^>]+(?:name|property)=["\'](?:description|og:description|twitter:description)["\']',
        )
        for pattern in patterns:
            match = re.search(pattern, raw, re.IGNORECASE)
            if match:
                preview = _clean_news_text(match.group(1), 320)
                if len(preview) >= 35:
                    return preview
    except Exception:
        pass
    return ""


def _ticker_news_terms(ticker: str, company_name: str = "") -> set[str]:
    terms = {str(ticker or "").upper()}
    aliases = {
        "SPY": {"SPY", "S&P 500", "SPDR S&P 500"},
        "QQQ": {"QQQ", "NASDAQ 100", "NASDAQ-100", "INVESCO QQQ"},
        "IWM": {"IWM", "RUSSELL 2000"},
        "DIA": {"DIA", "DOW JONES", "DOW 30"},
    }
    terms.update(aliases.get(str(ticker or "").upper(), set()))
    ignored = {"inc", "incorporated", "corp", "corporation", "company", "holdings", "plc", "ltd", "limited", "the", "etf", "trust"}
    name_words = [word for word in re.findall(r"[A-Za-z0-9]+", company_name) if word.lower() not in ignored and len(word) >= 3]
    if name_words:
        terms.add(name_words[0])
    return {term for term in terms if term}


def _title_mentions_ticker(title: str, terms: set[str]) -> bool:
    normalized_title = " ".join(str(title or "").upper().split())
    return any(
        re.search(rf"(?<![A-Z0-9]){re.escape(str(term).upper())}(?![A-Z0-9])", normalized_title)
        for term in terms
    )


def _fetch_yahoo_news_articles(ticker: str, max_articles: int = 8) -> list[dict]:
    params = urllib.parse.urlencode({
        "q": str(ticker).upper(),
        "quotesCount": 1,
        "newsCount": max(20, max_articles * 3),
        "enableFuzzyQuery": "false",
        "newsQueryId": "news_cie_vespa",
        "enableNavLinks": "false",
    })
    url = f"https://query2.finance.yahoo.com/v1/finance/search?{params}"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    payload = json.load(urllib.request.urlopen(req, timeout=12))
    quotes = payload.get("quotes") or []
    company_name = ""
    for quote in quotes:
        if str(quote.get("symbol", "")).upper() == str(ticker).upper():
            company_name = quote.get("longname") or quote.get("shortname") or ""
            break
    if company_name:
        _NEWS_COMPANY_NAME_CACHE[str(ticker).upper()] = str(company_name)
    terms = _ticker_news_terms(ticker, company_name)
    now_ts = time.time()
    cutoff = now_ts - 10 * 24 * 60 * 60
    articles = []
    seen = set()
    for item in payload.get("news") or []:
        title = _clean_news_text(item.get("title"), 240)
        published_ts = int(item.get("providerPublishTime") or 0)
        related = {str(symbol).upper() for symbol in (item.get("relatedTickers") or [])}
        directly_relevant = _title_mentions_ticker(title, terms)
        if not title or published_ts < cutoff or published_ts > now_ts + 300 or not directly_relevant or str(ticker).upper() not in related:
            continue
        dedupe_key = re.sub(r"[^a-z0-9]+", " ", title.lower()).strip()
        if dedupe_key in seen:
            continue
        seen.add(dedupe_key)
        link = str(item.get("link") or "")
        if not link.startswith(("http://", "https://")):
            link = ""
        articles.append({
            "title": title,
            "source": _clean_news_text(item.get("publisher"), 80) or "Unknown source",
            "feed_provider": "yahoo",
            "url": link,
            "published_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(published_ts)),
            "published_ts": published_ts,
            "age_hours": round(max(0.0, (time.time() - published_ts) / 3600.0), 1),
            "excerpt": "",
        })
        if len(articles) >= max_articles:
            break
    return articles


def _fetch_google_news_articles(ticker: str, max_articles: int = 8) -> list[dict]:
    company_name = _NEWS_COMPANY_NAME_CACHE.get(str(ticker).upper(), "")
    alias_terms = sorted(
        _ticker_news_terms(ticker, company_name) - {str(ticker).upper()},
        key=lambda value: (len(value), value),
    )
    company_term = alias_terms[0] if alias_terms else ""
    query_text = f'"{str(ticker).upper()}" {company_term} stock when:7d'.strip()
    query = urllib.parse.quote(query_text)
    url = f"https://news.google.com/rss/search?q={query}&hl=en-US&gl=US&ceid=US:en"
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    root = ET.parse(urllib.request.urlopen(req, timeout=12)).getroot()
    terms = _ticker_news_terms(ticker, company_name)
    now_ts = time.time()
    cutoff = now_ts - 10 * 24 * 60 * 60
    articles = []
    seen = set()
    for item in root.findall(".//item"):
        title_node = item.find("title")
        link_node = item.find("link")
        source_node = item.find("source")
        date_node = item.find("pubDate")
        title = _clean_news_text(title_node.text if title_node is not None else "", 240)
        if not title or not _title_mentions_ticker(title, terms):
            continue
        clean_title = title.rsplit(" - ", 1)[0].strip()
        dedupe_key = re.sub(r"[^a-z0-9]+", " ", clean_title.lower()).strip()
        if dedupe_key in seen:
            continue
        seen.add(dedupe_key)
        published_ts = 0
        if date_node is not None and date_node.text:
            try:
                from email.utils import parsedate_to_datetime
                published_ts = int(parsedate_to_datetime(date_node.text).timestamp())
            except Exception:
                published_ts = 0
        if published_ts and (published_ts < cutoff or published_ts > now_ts + 300):
            continue
        link = str(link_node.text if link_node is not None else "")
        articles.append({
            "title": clean_title,
            "source": _clean_news_text(source_node.text if source_node is not None else "", 80) or "Google News source",
            "feed_provider": "google",
            "url": link if link.startswith(("http://", "https://")) else "",
            "published_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(published_ts)) if published_ts else "",
            "published_ts": published_ts,
            "age_hours": round(max(0.0, (time.time() - published_ts) / 3600.0), 1) if published_ts else None,
            "excerpt": "",
        })
        if len(articles) >= max_articles:
            break
    return articles


def _fetch_news_article_metadata(ticker: str, max_articles: int = 8) -> tuple[list[dict], dict]:
    """Fetch lightweight article metadata and report provider health."""
    articles = []
    provider_status = {"yahoo": "not_checked", "google": "not_checked", "errors": []}
    try:
        articles = _fetch_yahoo_news_articles(ticker, max_articles)
        provider_status["yahoo"] = "ok" if articles else "empty"
    except Exception as exc:
        provider_status["yahoo"] = "error"
        provider_status["errors"].append(f"Yahoo: {type(exc).__name__}")
        print(f"[ai_indicator] Yahoo news fetch error for {ticker}: {exc}")
    if len(articles) < 3:
        try:
            google_articles = _fetch_google_news_articles(ticker, max_articles)
            provider_status["google"] = "ok" if google_articles else "empty"
            existing = {re.sub(r"[^a-z0-9]+", " ", article["title"].lower()).strip() for article in articles}
            for article in google_articles:
                key = re.sub(r"[^a-z0-9]+", " ", article["title"].lower()).strip()
                if key not in existing:
                    articles.append(article)
                    existing.add(key)
                if len(articles) >= max_articles:
                    break
        except Exception as exc:
            provider_status["google"] = "error"
            provider_status["errors"].append(f"Google: {type(exc).__name__}")
            print(f"[ai_indicator] Google news fetch error for {ticker}: {exc}")
    articles.sort(key=lambda item: int(item.get("published_ts") or 0), reverse=True)
    return articles[:max_articles], provider_status


def _fetch_news_article_metadata_cached(ticker: str, max_articles: int = 8) -> tuple[list[dict], dict]:
    """Coalesce the same public ticker feed across users for one poll cycle."""
    cache_key = (str(ticker or "").upper(), int(max_articles))
    cached = _NEWS_METADATA_CACHE.get(cache_key, 50)
    if cached is not None:
        return copy.deepcopy(cached["articles"]), copy.deepcopy(cached["provider_status"])
    with _NEWS_METADATA_CACHE.with_inflight_lock(cache_key):
        cached = _NEWS_METADATA_CACHE.get(cache_key, 50)
        if cached is None:
            articles, provider_status = _fetch_news_article_metadata(ticker, max_articles)
            cached = {"articles": articles, "provider_status": provider_status}
            _NEWS_METADATA_CACHE.set(cache_key, cached)
        return copy.deepcopy(cached["articles"]), copy.deepcopy(cached["provider_status"])


def _add_news_article_previews(articles: list[dict]) -> list[dict]:
    """Add bounded publisher metadata previews after a changed feed is detected."""
    articles = [dict(article) for article in articles]
    preview_targets = [(index, article["url"]) for index, article in enumerate(articles[:5]) if article.get("url")]
    if preview_targets:
        with concurrent.futures.ThreadPoolExecutor(max_workers=min(5, len(preview_targets))) as executor:
            futures = {executor.submit(_article_preview, url): index for index, url in preview_targets}
            for future in concurrent.futures.as_completed(futures):
                articles[futures[future]]["excerpt"] = future.result()
    return articles


def _fetch_news_articles(ticker: str, max_articles: int = 8) -> list[dict]:
    """Fetch recent, directly attributable article evidence with bounded previews."""
    articles, _ = _fetch_news_article_metadata(ticker, max_articles)
    return _add_news_article_previews(articles)


def _fetch_news_headlines(ticker: str, max_headlines: int = 12) -> list[str]:
    """Backward-compatible title-only view used by older callers and audits."""
    return [article["title"] for article in _fetch_news_articles(ticker, max_headlines)]


