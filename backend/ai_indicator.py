def _fallback_signal(ctx: dict, available_cash: float, account_equity: float) -> dict:
    """Generates a basic signal using simple rules when Groq is unavailable."""
    price = ctx.get("price") or 0
    rsi = ctx.get("rsi") or 50
    macd_hist = ctx.get("macd_hist") or 0
    spy_trend = ctx.get("spy_trend", "NEUTRAL")
    vix_regime = ctx.get("vix_regime", "MEDIUM")
    atr = ctx.get("atr") or (price * 0.02)

    bull_score = 0
    bear_score = 0

    if rsi < 35:
        bull_score += 2
    elif rsi > 65:
        bear_score += 2

    if macd_hist > 0:
        bull_score += 1
    elif macd_hist < 0:
        bear_score += 1

    if spy_trend == "BULLISH":
        bull_score += 1
    elif spy_trend == "BEARISH":
        bear_score += 1

    if bull_score > bear_score:
        signal = "BUY"
        confidence = min(0.55 + bull_score * 0.05, 0.75)
        regime = "BULLISH"
    elif bear_score > bull_score:
        signal = "SELL"
        confidence = min(0.55 + bear_score * 0.05, 0.75)
        regime = "BEARISH"
    else:
        signal = "HOLD"
        confidence = 0.45
        regime = "NEUTRAL"

    # Leverage guidance from VIX
    leverage_map = {"LOW": "1.5x – Low VIX, moderate leverage OK", "MEDIUM": "1x – Normal conditions", "HIGH": "0.5x – High VIX, reduce exposure", "CRYPTO": "1x – Crypto: no leverage recommended"}
    leverage = leverage_map.get(vix_regime, "1x – Default")

    pos_pct = 0.10 if signal == "BUY" else 0.0
    pos_usd = round(available_cash * pos_pct, 2)

    if signal == "SELL":
        stop_loss = round(price + atr * 2, 8) if price else None
        sell_target = round(price - atr * 4, 8) if price else None
    else:
        stop_loss = round(price - atr * 2, 8) if price else None
        sell_target = round(price + atr * 4, 8) if price else None
        
    sell_target_pct = None
    if price and sell_target:
        sell_target_pct = round(abs(sell_target - price) / price * 100, 2)

    return {
        "signal": signal,
        "confidence": round(confidence, 2),
        "entry_price": round(price, 8) if price else None,
        "position_size_pct": pos_pct,
        "position_size_usd": pos_usd,
        "stop_loss": stop_loss,
        "sell_target": sell_target,
        "sell_target_pct": sell_target_pct,
        "leverage_guidance": leverage,
        "regime": regime,
        "technical_bias": regime if regime in {"BULLISH", "BEARISH"} else "NEUTRAL",
        "news_bias": "NEUTRAL",
        "decision_driver": "TECHNICAL",
        "setup_quality": "C" if signal != "HOLD" else "NO_TRADE",
        "entry_trigger": "Technical fallback confirms trend and momentum" if signal == "BUY" else "NONE",
        "exit_plan": "Exit on stop, target, or technical reversal",
        "invalidation_condition": "ATR stop or trend reversal",
        "summary": (
            f"Rule-based analysis for {ctx['ticker']}: RSI at {rsi:.1f}, "
            f"MACD {'positive' if macd_hist > 0 else 'negative'}, "
            f"SPY trend {spy_trend.lower()}, VIX regime {vix_regime.lower()}. "
            "Groq AI unavailable — using technical fallback."
        ),
        "key_catalyst": f"RSI: {rsi:.1f} | MACD: {'+' if macd_hist > 0 else ''}{macd_hist:.4f}",
        "risk_factors": f"Groq AI offline — limited analysis. VIX: {vix_regime}",
        "headline_count": ctx.get("headline_count", 0),
        "cached": False,
        "model": "rule-based-fallback",
    }


def _call_llm(
    prompt: str,
    system_msg: str,
    model: str,
    cfg,
    temperature: float = 0.2,
    max_tokens: int = 1500,
) -> tuple[str, str]:
    """
    Calls either Groq or local Ollama depending on the model name prefix.
    Returns: (raw_response_text, model_name_used)
    """
    is_ollama = model and (model.startswith("ollama/") or model.startswith("ollama:"))
    if is_ollama:
        ollama_model = model.split("/", 1)[-1] if "/" in model else model.split(":", 1)[-1]
        host = getattr(cfg, "OLLAMA_HOST", "http://localhost:11434")
        print(f"[ai_indicator] Routing to Ollama ({ollama_model}) at {host}…")
        
        import requests
        url = f"{host.rstrip('/')}/api/chat"
        payload = {
            "model": ollama_model,
            "messages": [
                {"role": "system", "content": system_msg},
                {"role": "user", "content": prompt}
            ],
            "format": "json",
            "stream": False,
            "keep_alive": "10m",
            "options": {
                "temperature": temperature
            }
        }
        
        try:
            response = requests.post(url, json=payload, timeout=90)
            if response.status_code == 404:
                try:
                    err_data = response.json()
                    err_msg = err_data.get("error", "")
                except:
                    err_msg = ""
                if "not found" in err_msg.lower():
                    raise ValueError(f"Ollama model '{ollama_model}' not found. Run 'ollama pull {ollama_model}' locally to install it.")
            response.raise_for_status()
            res_json = response.json()
            raw_content = res_json["message"]["content"].strip()
            
            # Strip Chain-of-Thought <think> blocks (often produced by DeepSeek-R1)
            raw_content = re.sub(r"<think>.*?</think>", "", raw_content, flags=re.DOTALL).strip()
            
            return raw_content, model
        except requests.exceptions.ConnectionError as ce:
            raise ConnectionError(f"Could not connect to Ollama at {host}. Make sure the Ollama app is running locally or check OLLAMA_HOST settings.") from ce
        except Exception as exc:
            raise exc
    else:
        # Default Groq flow
        groq_key = getattr(cfg, "GROQ_API_KEY", "")
        if not _GROQ_AVAILABLE or not groq_key or groq_key in ("", "your_groq_api_key_here"):
            raise ValueError("Groq API key not configured or library missing.")
            
        from groq import Groq
        client = Groq(api_key=groq_key)
        
        request = {
            "messages": [
                {"role": "system", "content": system_msg},
                {"role": "user", "content": prompt},
            ],
            "model": model,
            "temperature": temperature,
            "max_tokens": max_tokens,
        }
        if model.startswith("openai/gpt-oss-"):
            # GPT-OSS otherwise defaults to a larger reasoning budget, which
            # can exhaust max_tokens before emitting the requested JSON.
            request["reasoning_effort"] = "low"
            request["include_reasoning"] = False
        try:
            response = client.chat.completions.create(
                **request,
                response_format={"type": "json_object"},
            )
        except Exception as exc:
            # An available Groq model can still fail provider-side strict JSON
            # validation. Retry the same JSON-only prompt without the strict
            # response format instead of cascading to another model.
            if "json_validate_failed" not in str(exc):
                raise
            response = client.chat.completions.create(**request)
        raw_content = (response.choices[0].message.content or "").strip()
        # Normalize occasional markdown/reasoning wrappers from the non-strict
        # retry so existing callers can continue to use json.loads directly.
        raw_content = re.sub(r"<think>.*?</think>", "", raw_content, flags=re.DOTALL).strip()
        if raw_content.startswith("```"):
            raw_content = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw_content, flags=re.IGNORECASE).strip()
        first_brace = raw_content.find("{")
        last_brace = raw_content.rfind("}")
        if first_brace >= 0 and last_brace > first_brace:
            raw_content = raw_content[first_brace:last_brace + 1]
        if not raw_content:
            finish_reason = getattr(response.choices[0], "finish_reason", "unknown")
            raise ValueError(f"Groq model {model} returned no JSON (finish_reason={finish_reason}).")
        try:
            json.loads(raw_content)
        except json.JSONDecodeError as exc:
            raise ValueError(f"Groq model {model} returned invalid JSON: {exc}") from exc
        return raw_content, model


