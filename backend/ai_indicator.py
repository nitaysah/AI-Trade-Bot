def _config_number(cfg, name: str, default: float) -> float:
    try:
        return float(getattr(cfg, name, default))
    except (TypeError, ValueError):
        return float(default)


def build_quant_assessment(
    ctx: dict,
    sentiment: dict = None,
    cfg=None,
    position: dict = None,
) -> dict:
    """Build an auditable long-only signal from independent evidence groups.

    The LLM may explain this assessment, but cannot replace its signal, score,
    levels, or risk/reward gate. Scores are setup-quality measures, not a
    probability of future profit.
    """
    cfg = cfg or get_user_config()
    sentiment = sentiment or {}
    price = float(ctx.get("price") or 0.0)
    atr = float(ctx.get("atr") or (price * 0.02 if price else 0.0))
    rsi = float(ctx.get("rsi") if ctx.get("rsi") is not None else 50.0)
    macd_hist = float(ctx.get("macd_hist") or 0.0)
    trend = str(ctx.get("ema_trend") or "UNKNOWN").upper()
    spy_trend = str(ctx.get("spy_trend") or "NEUTRAL").upper()
    sector_trend = str(ctx.get("sector_trend") or "NEUTRAL").upper()
    crossover = str(ctx.get("macd_crossover") or "NONE").upper()
    support = float(ctx.get("support") or 0.0)
    resistance = float(ctx.get("resistance") or 0.0)
    ema21 = float(ctx.get("ema_21") or 0.0)
    volume_ratio = float(ctx.get("volume_ratio") or 0.0)
    volatility_regime = str(ctx.get("vix_regime") or "UNKNOWN").upper()
    news_direction = sentiment_direction(
        sentiment.get("score", 0.0), sentiment.get("confidence", 0.0), cfg
    )

    minimum_score = max(50.0, min(95.0, _config_number(cfg, "AI_MIN_SETUP_SCORE", 70)))
    minimum_rr = max(1.0, min(5.0, _config_number(cfg, "AI_MIN_REWARD_RISK", 1.5)))
    max_entry_rsi = max(55.0, min(85.0, _config_number(cfg, "AI_MAX_ENTRY_RSI", 72)))
    min_volume_ratio = max(0.0, min(5.0, _config_number(cfg, "AI_MIN_VOLUME_RATIO", 0.80)))
    require_volume = bool(getattr(cfg, "AI_REQUIRE_VOLUME_CONFIRMATION", False))

    bullish_score = 0.0
    bearish_score = 0.0
    bullish_evidence = []
    bearish_evidence = []
    cautions = []

    # Trend structure: one evidence family, preventing EMA/SMA double-counting.
    if trend == "STRONG_BULL":
        bullish_score += 25
        bullish_evidence.append("Strong bullish EMA/SMA structure")
    elif trend == "BULL":
        bullish_score += 20
        bullish_evidence.append("Bullish EMA structure")
    elif trend == "STRONG_BEAR":
        bearish_score += 25
        bearish_evidence.append("Strong bearish EMA/SMA structure")
    elif trend == "BEAR":
        bearish_score += 20
        bearish_evidence.append("Bearish EMA structure")
    else:
        cautions.append("Mixed or unavailable trend structure")

    # Momentum: MACD and RSI share a capped 25-point family.
    if macd_hist > 0:
        bullish_score += 10
        bullish_evidence.append("MACD momentum is positive")
    elif macd_hist < 0:
        bearish_score += 10
        bearish_evidence.append("MACD momentum is negative")
    if crossover == "BULLISH_CROSS":
        bullish_score += 5
        bullish_evidence.append("Fresh bullish MACD crossover")
    elif crossover == "BEARISH_CROSS":
        bearish_score += 5
        bearish_evidence.append("Fresh bearish MACD crossover")

    if 52 <= rsi <= 68:
        bullish_score += 10
        bullish_evidence.append(f"RSI {rsi:.1f} confirms bullish momentum")
    elif 32 <= rsi <= 48:
        bearish_score += 8
        bearish_evidence.append(f"RSI {rsi:.1f} confirms weak momentum")
    elif rsi > max_entry_rsi:
        bearish_score += 5
        cautions.append(f"RSI {rsi:.1f} is above the {max_entry_rsi:.0f} entry limit")
    elif rsi < 30:
        bullish_score += 3
        cautions.append(f"RSI {rsi:.1f} is oversold; reversal still needs confirmation")

    # Prior-bar structure. Support/resistance excludes the decision candle.
    breakout = bool(price and resistance and price > resistance)
    breakdown = bool(price and support and price < support)
    if breakout:
        bullish_score += 15
        bullish_evidence.append(f"Price broke prior resistance at ${resistance:.2f}")
    elif price and ema21 and price >= ema21:
        bullish_score += 8
        bullish_evidence.append("Price is holding above EMA21")
    if breakdown:
        bearish_score += 15
        bearish_evidence.append(f"Price broke prior support at ${support:.2f}")
    elif price and ema21 and price < ema21:
        bearish_score += 8
        bearish_evidence.append("Price is below EMA21")

    # Volume confirms the currently dominant technical side; it is never a
    # directional signal by itself.
    volume_ok = volume_ratio >= min_volume_ratio if volume_ratio > 0 else not require_volume
    if volume_ratio > 0 and volume_ok:
        if bullish_score > bearish_score:
            bullish_score += 10
            bullish_evidence.append(f"Volume is {volume_ratio:.2f}x its 20-bar average")
        elif bearish_score > bullish_score:
            bearish_score += 10
            bearish_evidence.append(f"Volume is {volume_ratio:.2f}x its 20-bar average")
    elif require_volume:
        cautions.append("Required volume confirmation is missing")
    elif volume_ratio > 0:
        cautions.append(f"Volume is light at {volume_ratio:.2f}x average")

    # Macro/sector and news have deliberately small weights.
    if spy_trend == "BULLISH":
        bullish_score += 5
        bullish_evidence.append("Broad market trend is bullish")
    elif spy_trend == "BEARISH":
        bearish_score += 5
        bearish_evidence.append("Broad market trend is bearish")
    if sector_trend == "BULLISH":
        bullish_score += 5
        bullish_evidence.append("Sector trend confirms the long side")
    elif sector_trend == "BEARISH":
        bearish_score += 5
        bearish_evidence.append("Sector trend confirms the bearish side")
    if news_direction == "BULLISH":
        bullish_score += 5
    elif news_direction == "BEARISH":
        bearish_score += 5

    # Non-directional risk penalties reduce both sides rather than pretending
    # volatility or an event predicts direction.
    if volatility_regime == "HIGH":
        bullish_score = max(0.0, bullish_score - 7.0)
        bearish_score = max(0.0, bearish_score - 7.0)
        cautions.append("High VIX regime reduces setup quality and size")
    days_to_earnings = ctx.get("days_to_earnings")
    if days_to_earnings is not None:
        try:
            if 0 <= int(days_to_earnings) <= 3:
                bullish_score = max(0.0, bullish_score - 10.0)
                bearish_score = max(0.0, bearish_score - 10.0)
                cautions.append(f"Earnings event risk in {int(days_to_earnings)} day(s)")
        except (TypeError, ValueError):
            pass

    required_fields = ("price", "atr", "rsi", "macd_hist", "ema_9", "ema_21", "ema_50", "support", "resistance")
    present_count = sum(ctx.get(field) is not None for field in required_fields)
    data_quality_score = round(100.0 * present_count / len(required_fields), 1)
    quality_points = data_quality_score / 10.0
    bullish_score += quality_points
    bearish_score += quality_points
    bullish_score = round(min(100.0, bullish_score), 1)
    bearish_score = round(min(100.0, bearish_score), 1)

    if not price or not atr:
        cautions.append("Price or ATR data is unavailable")

    # Coherent structural risk levels and available reward/risk.
