def normalize_ai_timeframe(timeframe: str) -> str:
    """Return a supported canonical technical-decision timeframe."""
    raw = str(timeframe or AI_CANDLE_TIMEFRAME).strip()
    if raw in AI_TIMEFRAME_SPECS:
        return raw
    return AI_TIMEFRAME_ALIASES.get(raw.upper().replace(" ", ""), AI_CANDLE_TIMEFRAME)


