def sentiment_percentage(score: float) -> float:
    """Convert the model's -1..+1 score to the UI's 0..100% scale."""
    try:
        normalized = float(score)
    except (TypeError, ValueError):
        normalized = 0.0
    return max(0.0, min(100.0, (normalized + 1.0) * 50.0))


def sentiment_direction(score: float, confidence: float, cfg=None) -> str:
    """Return BULLISH/BEARISH/NEUTRAL using the configured percentage bands."""
    cfg = cfg or get_user_config()
    try:
        confidence_floor = float(getattr(cfg, "AI_NEWS_MIN_CONFIDENCE", 0.40))
    except (TypeError, ValueError):
        confidence_floor = 0.40
    try:
        bullish_pct = float(getattr(cfg, "SENTIMENT_BULLISH_PERCENTAGE", 70))
    except (TypeError, ValueError):
        bullish_pct = 70.0
    try:
        bearish_pct = float(getattr(cfg, "SENTIMENT_BEARISH_PERCENTAGE", 30))
    except (TypeError, ValueError):
        bearish_pct = 30.0

    news_pct = sentiment_percentage(score)
    if float(confidence or 0.0) < confidence_floor:
        return "NEUTRAL"
    if news_pct >= bullish_pct:
        return "BULLISH"
    if news_pct <= bearish_pct:
        return "BEARISH"
    return "NEUTRAL"


def apply_news_alignment(result: dict, sentiment: dict, cfg=None, has_position: bool = False) -> dict:
    """Attach news metadata and veto contradictory flat entries when configured.

    News should confirm an entry, not blindly override technical/risk logic.
    Existing positions may still exit on technical or protective conditions.
    """
    cfg = cfg or get_user_config()
    score = float(sentiment.get("score", 0.0) or 0.0)
    confidence = float(sentiment.get("confidence", 0.0) or 0.0)
    news_pct = round(sentiment_percentage(score), 1)
    news_dir = sentiment_direction(score, confidence, cfg)
    # Preserve the original model decision if this result is being reloaded
    # from cache after a prior alignment pass.
    model_signal = str(result.get("model_signal") or result.get("signal", "HOLD")).upper()
    mode = str(getattr(cfg, "AI_NEWS_ALIGNMENT_MODE", "veto_conflicting_entries") or "off").lower()

    result["model_signal"] = model_signal
    result["sentiment_score"] = round(max(-1.0, min(1.0, score)), 3)
    result["sentiment_confidence"] = round(max(0.0, min(1.0, confidence)), 3)
    result["sentiment_pct"] = news_pct
    result["sentiment_direction"] = news_dir
    if sentiment.get("summary"):
        result["sentiment_summary"] = str(sentiment["summary"])
    if sentiment.get("key_factor"):
        result["sentiment_key_factor"] = str(sentiment["key_factor"])
    if sentiment.get("analysis_model"):
        result["news_analysis_model"] = str(sentiment["analysis_model"])
    if isinstance(sentiment.get("headlines"), list):
        result["news_headlines"] = [
            str(headline).strip() for headline in sentiment["headlines"][:5]
            if str(headline).strip()
        ]
    if isinstance(sentiment.get("articles"), list):
        result["news_articles"] = [
            {
                "title": _clean_news_text(article.get("title"), 240),
                "source": _clean_news_text(article.get("source"), 80),
                "feed_provider": str(article.get("feed_provider") or ""),
                "url": str(article.get("url") or "") if str(article.get("url") or "").startswith(("http://", "https://")) else "",
                "published_at": str(article.get("published_at") or ""),
                "age_hours": article.get("age_hours"),
                "excerpt": _clean_news_text(article.get("excerpt"), 320),
                "summary": _clean_news_text(article.get("summary"), 280),
                "sentiment": str(article.get("sentiment") or "NEUTRAL").upper(),
                "impact": str(article.get("impact") or "LOW").upper(),
                "relevance": str(article.get("relevance") or "DIRECT").upper(),
                "reason": _clean_news_text(article.get("reason"), 240),
            }
            for article in sentiment["articles"][:5]
            if isinstance(article, dict) and _clean_news_text(article.get("title"), 240)
        ]
    headline_count = int(sentiment.get("headline_count", result.get("headline_count", 0)) or 0)
    if headline_count >= 6 and confidence >= 0.65:
        result["news_coverage_quality"] = "ROBUST"
    elif headline_count >= 3 and confidence >= 0.40:
        result["news_coverage_quality"] = "MODERATE"
    else:
        result["news_coverage_quality"] = "LIMITED"
    result["news_alignment"] = "ALIGNED"
    result["news_alignment_applied"] = False
    if model_signal == "HOLD":
        result["news_alignment_reason"] = (
            f"News is {news_dir.lower()}, but news alone does not override a quantitative HOLD decision."
        )
    else:
        result["news_alignment_reason"] = (
            f"News is {news_dir.lower()} and is used only as confirmation for the {model_signal} decision."
        )

    conflicting_entry = (
        not has_position
        and mode in {"veto_conflicting_entries", "veto", "guard"}
        and ((model_signal == "SELL" and news_dir == "BULLISH")
             or (model_signal == "BUY" and news_dir == "BEARISH"))
    )
    if conflicting_entry:
        result["signal"] = "HOLD"
        result["position_size_pct"] = 0.0
        result["position_size_usd"] = 0.0
        result["quant_gates_passed"] = False
        result["news_alignment"] = "CONFLICT_VETO"
        result["news_alignment_applied"] = True
        result["news_alignment_reason"] = (
            f"Entry blocked: model {model_signal} conflicts with {news_pct:.0f}% "
            f"{news_dir.lower()} news sentiment. Waiting for confirmation."
        )
        result["reason"] = result["news_alignment_reason"]
        result["wait_reason"] = result["news_alignment_reason"]
        result["entry_trigger"] = (
            f"WAIT: require non-conflicting news or a stronger completed-candle {model_signal} confirmation."
        )
        result["summary"] = (
            f"Technical gates produced {model_signal}, while canonical news is {news_dir.lower()} at {news_pct:.0f}/100. "
            "Final decision: HOLD because the configured news conflict guard blocked the new entry."
        )
    elif has_position and model_signal == "SELL" and news_dir == "BULLISH":
        result["news_alignment"] = "RISK_EXIT_OVERRIDE"
        result["news_alignment_reason"] = (
            f"SELL retained as a position/risk exit despite {news_pct:.0f}% "
            "bullish news sentiment."
        )

    return result


def attach_sentiment_metadata(sentiment: dict, cfg=None) -> dict:
    """Normalize raw -1..+1 sentiment into the canonical 0..100 UI fields."""
    cfg = cfg or get_user_config()
    result = dict(sentiment or {})
    try:
        score = float(result.get("score", 0.0) or 0.0)
    except (TypeError, ValueError):
        score = 0.0
    try:
        confidence = float(result.get("confidence", 0.0) or 0.0)
    except (TypeError, ValueError):
        confidence = 0.0

    score = max(-1.0, min(1.0, score))
    confidence = max(0.0, min(1.0, confidence))
    result["score"] = round(score, 3)
    result["confidence"] = round(confidence, 3)
    result["sentiment_pct"] = round(sentiment_percentage(score), 1)
    result["sentiment_direction"] = sentiment_direction(score, confidence, cfg)
    result["summary"] = canonicalize_sentiment_summary(
        result.get("summary", ""),
        result["sentiment_direction"],
        result["sentiment_pct"],
        confidence,
    )
    return result


def canonicalize_sentiment_summary(summary: str, direction: str, percentage: float, confidence: float) -> str:
    """Prevent free-form news prose from contradicting the canonical score."""
    text = " ".join(str(summary or "").split()).strip()
    sentences = [sentence.strip() for sentence in re.split(r"(?<=[.!?])\s+", text) if sentence.strip()]
    factual_sentences = []
    for sentence in sentences:
        lower = sentence.lower()
        is_classification_only = (
            "aggregate headline tone" in lower
            or "overall headline tone" in lower
            or lower.startswith("the news tone is")
        )
        if not is_classification_only:
            factual_sentences.append(sentence)
        if len(factual_sentences) == 2:
            break
    facts = " ".join(factual_sentences).strip()
    if not facts:
        facts = "The available headlines were evaluated as a separate news evidence stream."
    elif facts[-1] not in ".!?":
        facts += "."
    return (
        f"{facts} Aggregate headline tone is {str(direction).lower()} "
        f"at {float(percentage):.0f}/100 with {float(confidence) * 100:.0f}% classifier confidence."
    )


