def apply_quant_position_sizing(result: dict, available_cash: float, account_equity: float, cfg=None) -> dict:
    """Cap BUY notional by both conviction and stop-distance account risk."""
    cfg = cfg or get_user_config()
    if str(result.get("signal")).upper() != "BUY":
        result["position_size_pct"] = 0.0
        result["position_size_usd"] = 0.0
        return result
    cash = max(0.0, float(available_cash or 0.0))
    equity = max(0.0, float(account_equity or cash))
    entry = float(result.get("entry_price") or 0.0)
    stop = float(result.get("stop_loss") or 0.0)
    risk_per_trade = _config_number(cfg, "RISK_PER_TRADE", 0.01)
    max_position_pct = _config_number(cfg, "MAX_POSITION_PCT", 0.25)
    if risk_per_trade > 1:
        risk_per_trade /= 100.0
    if max_position_pct > 1:
        max_position_pct /= 100.0
    risk_per_trade = max(0.001, min(0.05, risk_per_trade))
    max_position_pct = max(0.01, min(1.0, max_position_pct))
    conviction_fraction = float(result.get("conviction_allocation_pct", result.get("position_size_pct", 0.0)) or 0.0)
    conviction_cap = cash * max(0.0, min(1.0, conviction_fraction))
    portfolio_cap = equity * max_position_pct
    risk_budget = equity * risk_per_trade
    stop_distance_pct = (entry - stop) / entry if entry > 0 and 0 < stop < entry else 0.0
    risk_limited_notional = risk_budget / stop_distance_pct if stop_distance_pct > 0 else 0.0
    notional = min(cash, conviction_cap, portfolio_cap, risk_limited_notional) if risk_limited_notional > 0 else 0.0
    result["position_size_usd"] = round(max(0.0, notional), 2)
    result["position_size_pct"] = round(notional / cash, 4) if cash > 0 else 0.0
    result["risk_budget_usd"] = round(risk_budget, 2)
    result["stop_distance_pct"] = round(stop_distance_pct * 100.0, 3)
    return result


